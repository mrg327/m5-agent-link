#!/usr/bin/env python3
"""Generate the Mote's look for the firmware, the Atlas, the favicon and the CLI.

Reads design/mote/mote.toml and writes the files in OUTPUTS (design/mote/README.md):
  python3 design/mote/gen.py            regenerate every output
  python3 design/mote/gen.py --check    exit 1 if a committed output differs
                                        (run by scripts/check structure)

The halo's alpha is peak x (1 - t)^exponent, t going from 0 at the core's edge to 1 at the halo's.
The firmware gets it as a falloff table and pre-rendered A8 sprites; the Atlas and the favicon get
it as gradient stops. Python 3.11 stdlib only.
"""

from __future__ import annotations

import argparse
import math
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
PROFILE = ROOT / "design/mote/mote.toml"
SELF = "design/mote/gen.py"
SRC = "design/mote/mote.toml"
BANNER = f"GENERATED by {SELF} from {SRC}. Do not edit."

OUT_C = "firmware/components/core/src/mote_look.h"
OUT_CSS = "atlas/css/mote.generated.css"
OUT_SVG = "atlas/img/mote.svg"
OUT_FAVICON = "atlas/img/favicon-{size}.svg"
OUT_RUST = "daemon/crates/agentlink/src/mote.rs"

SUPERSAMPLE = 4  # samples per pixel side when rendering a sprite
SIZE_ORDER = ("s", "tucked", "m", "l", "ember")
_LEVELS = ("lit", "idle", "night", "ember")
_BREATH = ("period_ms", "halo_min", "halo_max")
_FLARE = ("halo_scale", "rise_ms", "fall_ms")


class ProfileError(ValueError):
    """The profile is missing a key or holds a value of the wrong kind."""


@dataclass(frozen=True)
class Size:
    """One size of the orb, in px.

    Attributes:
        name: The key under [sizes], e.g. "s".
        core_r: Radius of the solid core.
        halo_r: Radius of the halo; 0 means no halo.
        sprite: Whether the firmware header carries a pre-rendered halo sprite.
    """

    name: str
    core_r: float
    halo_r: float
    sprite: bool


@dataclass(frozen=True)
class Look:
    """The parsed profile."""

    rgb: tuple[int, int, int]
    halo_ratio: float
    halo_peak: float
    halo_exponent: float
    falloff_steps: int
    css_stops: int
    levels: dict[str, float]
    breath: dict[str, float]
    flare: dict[str, float]
    sizes: dict[str, Size]
    brand_size: str
    svg_size: str
    favicon: dict[str, Any]


def _get(table: dict[str, Any], key: str, kind: type | tuple[type, ...], where: str) -> Any:
    if key not in table:
        raise ProfileError(f"{where}: missing key {key!r}")
    val = table[key]
    if isinstance(val, bool) and kind is not bool:
        raise ProfileError(f"{where}.{key}: expected a number, got {val!r}")
    if not isinstance(val, kind):
        raise ProfileError(f"{where}.{key}: expected {kind}, got {val!r}")
    return val


def _rgb(text: str, where: str) -> tuple[int, int, int]:
    if len(text) != 7 or not text.startswith("#"):
        raise ProfileError(f"{where}: expected #RRGGBB, got {text!r}")
    v = int(text[1:], 16)
    return (v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF


def _table(doc: dict[str, Any], key: str) -> dict[str, Any]:
    val = doc.get(key)
    if not isinstance(val, dict):
        raise ProfileError(f"missing table [{key}]")
    return val


def load(path: Path) -> Look:
    """Parse and validate the profile.

    Raises:
        ProfileError: A key is missing or has the wrong kind.
    """
    with path.open("rb") as f:
        doc = tomllib.load(f)
    look = _table(doc, "look")
    num = (int, float)
    ratio = _get(look, "halo_ratio", list, "look")
    if len(ratio) != 2 or not all(isinstance(x, int | float) for x in ratio) or ratio[1] == 0:
        raise ProfileError("look.halo_ratio: expected [numerator, denominator]")
    halo_ratio = ratio[0] / ratio[1]
    sizes: dict[str, Size] = {}
    for name, t in _table(doc, "sizes").items():
        where = f"sizes.{name}"
        if not isinstance(t, dict):
            raise ProfileError(f"{where}: expected a table")
        core_r = float(_get(t, "core_r", num, where))
        halo_r = float(t.get("halo_r", core_r * halo_ratio))
        sprite = bool(t.get("sprite", False))
        if sprite and halo_r <= core_r:
            raise ProfileError(f"{where}: a sprite needs a halo wider than the core")
        sizes[name] = Size(name, core_r, halo_r, sprite)
    brand = _table(doc, "brand")
    fav = _table(doc, "favicon")
    for key in ("sizes", "disc", "rim", "rim_ratio", "orb_clock", "orb_offset", "core_ratio"):
        _get(fav, key, (list, str, int, float), "favicon")
    for key in ("size", "svg_size"):
        if brand.get(key) not in sizes:
            raise ProfileError(f"brand.{key}: unknown size {brand.get(key)!r}")
    return Look(
        rgb=_rgb(_get(look, "colour", str, "look"), "look.colour"),
        halo_ratio=halo_ratio,
        halo_peak=float(_get(look, "halo_peak", num, "look")),
        halo_exponent=float(_get(look, "halo_exponent", num, "look")),
        falloff_steps=int(_get(look, "falloff_steps", int, "look")),
        css_stops=int(_get(look, "css_stops", int, "look")),
        levels={k: float(_get(_table(doc, "levels"), k, num, "levels")) for k in _LEVELS},
        breath={k: float(_get(_table(doc, "breath"), k, num, "breath")) for k in _BREATH},
        flare={k: float(_get(_table(doc, "flare"), k, num, "flare")) for k in _FLARE},
        sizes=sizes,
        brand_size=str(brand["size"]),
        svg_size=str(brand["svg_size"]),
        favicon=fav,
    )


# ---- the falloff -------------------------------------------------------------------------------


def halo_alpha(look: Look, d: float, core_r: float, halo_r: float) -> float:
    """Halo alpha (0 to 1) at distance d from the centre; the peak inside the core."""
    if halo_r <= core_r or d >= halo_r:
        return 0.0
    if d <= core_r:
        return look.halo_peak
    t = (d - core_r) / (halo_r - core_r)
    return look.halo_peak * math.pow(1.0 - t, look.halo_exponent)


def halo_sprite(look: Look, size: Size) -> tuple[int, list[int]]:
    """Render the halo as an A8 sprite, centred, side = ceil(2 x halo radius).

    Returns:
        The side in px and side x side alpha values (0 to 255), row by row.
    """
    side = math.ceil(2 * size.halo_r)
    c = side / 2
    n = SUPERSAMPLE
    out = []
    for y in range(side):
        for x in range(side):
            acc = 0.0
            for j in range(n):
                for i in range(n):
                    dx = x + (i + 0.5) / n - c
                    dy = y + (j + 0.5) / n - c
                    acc += halo_alpha(look, math.hypot(dx, dy), size.core_r, size.halo_r)
            out.append(round(255 * acc / (n * n)))
    return side, out


def stops(look: Look, core_r: float, halo_r: float) -> list[tuple[float, float]]:
    """Gradient stops over the halo as (offset 0 to 1 of the halo radius, alpha 0 to 1)."""
    n = look.css_stops
    res = []
    for i in range(n + 1):
        t = i / n
        alpha = look.halo_peak * math.pow(1 - t, look.halo_exponent)
        res.append(((core_r + t * (halo_r - core_r)) / halo_r, alpha))
    return res


def ansi256(rgb: tuple[int, int, int]) -> int:
    """The nearest xterm 256-colour index (the 6x6x6 cube and the grey ramp)."""
    levels = (0, 95, 135, 175, 215, 255)
    best, best_d = 16, 1 << 30
    for idx in range(16, 256):
        if idx < 232:
            k = idx - 16
            c = (levels[k // 36], levels[(k // 6) % 6], levels[k % 6])
        else:
            g = 8 + 10 * (idx - 232)
            c = (g, g, g)
        d = sum((a - b) ** 2 for a, b in zip(c, rgb, strict=True))
        if d < best_d:
            best, best_d = idx, d
    return best


def _num(v: float, digits: int = 3) -> str:
    s = f"{v:.{digits}f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def _hex(rgb: tuple[int, int, int]) -> str:
    return "#{:02x}{:02x}{:02x}".format(*rgb)


def _a8(v: float) -> int:
    return round(255 * v)


# ---- outputs ------------------------------------------------------------------------------------


def gen_c(look: Look) -> str:
    """The firmware header: constants, the falloff table and the halo sprites."""
    r, g, b = look.rgb
    lines = [
        f"/* {BANNER} */",
        "/* The Mote's look (design/mote/README.md). Not yet read by the renderer. Sizes are",
        " * diameters in px; a level or an alpha is 0 to 255; times in ms. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"#define MOTE_LOOK_RGB 0x{r:02X}{g:02X}{b:02X}",
        f"#define MOTE_LOOK_HALO_PEAK {_a8(look.halo_peak)} /* halo alpha at the core's edge */",
        f"#define MOTE_LOOK_HALO_RATIO_PCT {round(100 * look.halo_ratio)} /* halo / core radius */",
    ]
    for k in _LEVELS:
        lines.append(f"#define MOTE_LOOK_LEVEL_{k.upper()} {_a8(look.levels[k])}")
    lines += [
        f"#define MOTE_LOOK_BREATH_MS {round(look.breath['period_ms'])}",
        f"#define MOTE_LOOK_BREATH_MIN {_a8(look.breath['halo_min'])} /* halo alpha scale */",
        f"#define MOTE_LOOK_BREATH_MAX {_a8(look.breath['halo_max'])}",
        f"#define MOTE_LOOK_FLARE_SCALE_PCT {round(100 * look.flare['halo_scale'])}",
        f"#define MOTE_LOOK_FLARE_RISE_MS {round(look.flare['rise_ms'])}",
        f"#define MOTE_LOOK_FLARE_FALL_MS {round(look.flare['fall_ms'])}",
        "",
    ]
    for s in _ordered(look):
        u = s.name.upper()
        lines.append(f"#define MOTE_LOOK_{u}_CORE_D {round(2 * s.core_r)}")
        lines.append(f"#define MOTE_LOOK_{u}_HALO_D {round(2 * s.halo_r)}")
    n = look.falloff_steps
    table = [_a8(halo_alpha(look, 1 + i / n, 1, 2)) for i in range(n)] + [0]
    lines += [
        "",
        f"/* Halo alpha at t = i / {n}, t 0 at the core's edge and 1 at the halo's. */",
        f"#define MOTE_LOOK_FALLOFF_STEPS {n}",
        "static const uint8_t mote_look_falloff[MOTE_LOOK_FALLOFF_STEPS + 1] = {",
        *_rows(table, 16),
        "};",
    ]
    for s in _ordered(look):
        if not s.sprite:
            continue
        side, data = halo_sprite(look, s)
        u = s.name.upper()
        lines += [
            "",
            f"/* Size {s.name}: the halo alone as an A8 sprite, centred; draw the core over it. */",
            f"#define MOTE_LOOK_{u}_SPRITE_SIDE {side}",
            f"static const uint8_t mote_look_halo_{s.name}"
            f"[MOTE_LOOK_{u}_SPRITE_SIDE * MOTE_LOOK_{u}_SPRITE_SIDE] = {{",
            *_rows(data, side if side <= 16 else math.ceil(side / 2)),
            "};",
        ]
    return "\n".join(lines) + "\n"


def _rows(vals: list[int], per: int) -> list[str]:
    return [
        "    " + " ".join(f"{v:3d}," for v in vals[i : i + per]) for i in range(0, len(vals), per)
    ]


def _ordered(look: Look) -> list[Size]:
    known = [look.sizes[k] for k in SIZE_ORDER if k in look.sizes]
    return known + [s for k, s in sorted(look.sizes.items()) if k not in SIZE_ORDER]


def _gradient(look: Look, rgb: str, with_core: bool) -> str:
    ratio_core = 1 / look.halo_ratio
    parts = []
    st = stops(look, ratio_core, 1.0)
    first = _num(100 * st[0][0], 2)
    if with_core:
        parts.append(f"{_hex(look.rgb)} 0 {first}%")
        parts.append(f"rgb({rgb} / {_num(st[0][1])}) {first}%")
    else:
        parts.append(f"rgb({rgb} / {_num(st[0][1])}) 0 {first}%")
    for off, a in st[1:-1]:
        parts.append(f"rgb({rgb} / {_num(a)}) {_num(100 * off, 2)}%")
    parts.append("transparent 100%")
    return "radial-gradient(circle closest-side, " + ", ".join(parts) + ")"


def gen_css(look: Look) -> str:
    """Atlas custom properties, the orb's gradients and the breath keyframes."""
    rgb = " ".join(str(c) for c in look.rgb)
    lines = [
        f"/* {BANNER} */",
        "/* The Mote's look (design/mote/README.md). Sizes are diameters; a gradient fills a",
        " * square element as wide as the halo. */",
        ":root {",
        f"  --mote-colour: {_hex(look.rgb)};",
        f"  --mote-rgb: {rgb};",
    ]
    for s in _ordered(look):
        lines.append(f"  --mote-{s.name}-core: {_num(2 * s.core_r)}px;")
        lines.append(f"  --mote-{s.name}-halo: {_num(2 * s.halo_r)}px;")
    brand = look.sizes[look.brand_size]
    lines += [
        f"  --mote-brand-core: {_num(2 * brand.core_r)}px;",
        f"  --mote-brand-halo: {_num(2 * brand.halo_r)}px;",
    ]
    for k in _LEVELS:
        lines.append(f"  --mote-level-{k}: {_num(look.levels[k])};")
    lines += [
        f"  --mote-breath-period: {_num(look.breath['period_ms'])}ms;",
        f"  --mote-breath-min: {_num(look.breath['halo_min'])};",
        f"  --mote-breath-max: {_num(look.breath['halo_max'])};",
        f"  --mote-flare-scale: {_num(look.flare['halo_scale'])};",
        f"  --mote-flare-rise: {_num(look.flare['rise_ms'])}ms;",
        f"  --mote-flare-fall: {_num(look.flare['fall_ms'])}ms;",
        f"  --mote-orb: {_gradient(look, rgb, True)};",
        f"  --mote-halo: {_gradient(look, rgb, False)};",
        "}",
        "",
        "/* The breath: put it on a halo-only layer, so the core stays steady. */",
        "@keyframes mote-breath {",
        "  0%,",
        "  100% {",
        f"    opacity: {_num(look.breath['halo_min'])};",
        "  }",
        "  50% {",
        f"    opacity: {_num(look.breath['halo_max'])};",
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def _svg_stops(look: Look, core_r: float, halo_r: float, indent: str) -> list[str]:
    col = _hex(look.rgb)
    st = stops(look, core_r, halo_r)
    out = [f'{indent}<stop offset="0" stop-color="{col}" stop-opacity="{_num(st[0][1])}"/>']
    out += [
        f'{indent}<stop offset="{_num(off, 4)}" stop-color="{col}" stop-opacity="{_num(a)}"/>'
        for off, a in st
    ]
    return out


def gen_svg(look: Look) -> str:
    """The orb at the brand's SVG size: halo gradient and core."""
    s = look.sizes[look.svg_size]
    side = _num(2 * s.halo_r)
    c = _num(s.halo_r)
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{side}" height="{side}" '
        f'viewBox="0 0 {side} {side}">',
        f"  <!-- {BANNER} -->",
        "  <title>The Mote</title>",
        "  <defs>",
        f'    <radialGradient id="halo" gradientUnits="userSpaceOnUse" cx="{c}" cy="{c}" r="{c}">',
        *_svg_stops(look, s.core_r, s.halo_r, "      "),
        "    </radialGradient>",
        "  </defs>",
        f'  <circle cx="{c}" cy="{c}" r="{c}" fill="url(#halo)"/>',
        f'  <circle cx="{c}" cy="{c}" r="{_num(s.core_r)}" fill="{_hex(look.rgb)}"/>',
        "</svg>",
    ]
    return "\n".join(lines) + "\n"


def gen_favicon(look: Look, size: int) -> str:
    """The favicon at one size: a black disc, a thin grey rim, the orb at about 1:30."""
    fav = look.favicon
    c = size / 2
    rim = max(1.0, size * float(fav["rim_ratio"]))
    disc_r = c - rim / 2
    inner_r = c - rim
    angle = math.radians(30 * float(fav["orb_clock"]))
    off = float(fav["orb_offset"]) * inner_r
    ox, oy = c + off * math.sin(angle), c - off * math.cos(angle)
    core_r = max(1.5, size * float(fav["core_ratio"]))
    halo_r = core_r * look.halo_ratio
    disc = _hex(_rgb(str(fav["disc"]), "favicon.disc"))
    rim_col = _hex(_rgb(str(fav["rim"]), "favicon.rim"))
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 {size} {size}">',
        f"  <!-- {BANNER} -->",
        "  <defs>",
        f'    <radialGradient id="halo" gradientUnits="userSpaceOnUse" cx="{_num(ox, 2)}" '
        f'cy="{_num(oy, 2)}" r="{_num(halo_r, 2)}">',
        *_svg_stops(look, core_r, halo_r, "      "),
        "    </radialGradient>",
        f'    <clipPath id="disc"><circle cx="{_num(c)}" cy="{_num(c)}" r="{_num(inner_r, 2)}"/>'
        "</clipPath>",
        "  </defs>",
        f'  <circle cx="{_num(c)}" cy="{_num(c)}" r="{_num(disc_r, 2)}" fill="{disc}" '
        f'stroke="{rim_col}" stroke-width="{_num(rim, 2)}"/>',
        '  <g clip-path="url(#disc)">',
        f'    <circle cx="{_num(ox, 2)}" cy="{_num(oy, 2)}" r="{_num(halo_r, 2)}" '
        'fill="url(#halo)"/>',
        f'    <circle cx="{_num(ox, 2)}" cy="{_num(oy, 2)}" r="{_num(core_r, 2)}" '
        f'fill="{_hex(look.rgb)}"/>',
        "  </g>",
        "</svg>",
    ]
    return "\n".join(lines) + "\n"


def gen_rust(look: Look) -> str:
    """The CLI's colour constants (not yet in the module tree)."""
    r, g, b = look.rgb
    return (
        f"// {BANNER}\n"
        "//! The Mote's colour for the CLI's status mark (design/mote/README.md). Not yet used.\n"
        "\n"
        "/// The Mote's warm white as 24-bit RGB.\n"
        f"pub const MOTE_RGB: (u8, u8, u8) = (0x{r:02X}, 0x{g:02X}, 0x{b:02X});\n"
        "\n"
        "/// The nearest xterm 256-colour index, for terminals without truecolor.\n"
        f"pub const MOTE_ANSI256: u8 = {ansi256(look.rgb)};\n"
    )


def outputs(look: Look) -> dict[str, str]:
    """Every output, as repository-relative path -> text."""
    out = {
        OUT_C: gen_c(look),
        OUT_CSS: gen_css(look),
        OUT_SVG: gen_svg(look),
        OUT_RUST: gen_rust(look),
    }
    for size in look.favicon["sizes"]:
        if not isinstance(size, int) or isinstance(size, bool):
            raise ProfileError(f"favicon.sizes: expected px as integers, got {size!r}")
        out[OUT_FAVICON.format(size=size)] = gen_favicon(look, size)
    return out


def main(argv: list[str] | None = None) -> int:
    """Regenerate the outputs, or with --check report the stale ones."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    ap.add_argument("--check", action="store_true", help="exit 1 if a committed output is stale")
    args = ap.parse_args(argv)
    try:
        files = outputs(load(PROFILE))
    except (ProfileError, tomllib.TOMLDecodeError) as e:
        print(f"{SRC}:1: S-GEN-01 {e} - fix the profile", file=sys.stderr)
        return 1
    if args.check:
        stale = [
            p
            for p, text in files.items()
            if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != text
        ]
        for p in stale:
            print(f"{p}:1: S-GEN-01 stale Mote output - run: python3 {SELF}", file=sys.stderr)
        if stale:
            return 1
        print(f"mote look up to date ({len(files)} files)")
        return 0
    for p, text in files.items():
        dest = ROOT / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files from {SRC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
