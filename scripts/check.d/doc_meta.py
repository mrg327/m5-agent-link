#!/usr/bin/env python3
"""Check design and convention docs' front matter, and generate the design-doc index (DOC-8..11).

Usage: python3 scripts/check.d/doc_meta.py [--write] [--stale DAYS [--status STATUS]]

  (no option)   validate the front matter of every docs/design/**/*.md (except the index,
                docs/design/README.md) and docs/conventions/*.md, then check that the index in
                docs/design/README.md (between the index markers) is what the front matter makes.
                Exit 1 on any problem.
  --write       the same checks, but rewrite the index instead of failing when it is out of date.
  --stale DAYS  report only, exit 0: list the docs whose last_reviewed is more than DAYS days old
                (DOC-10; the scheduled job that files this as a tracker issue is planned).
  --status S    with --stale: only docs with this status (the DOC-10 report uses `implemented`).

Front matter (docs/conventions/docs.md §2):
  status         required; draft | accepted | implemented | superseded               DOC-9
  owner          required; a role from OWNERS below, never a person                   DOC-8
  last_reviewed  required; YYYY-MM-DD, a real date, not in the future                  DOC-10
  issue          optional; an issue ID or a [list]; each must have a file in issues/   DOC-8
  superseded_by  required when status is superseded, otherwise absent; a relative
                 path to an existing doc in the checked set                             DOC-9
  summary        optional; the index's "What it covers" text (otherwise the first
                 sentence of the doc's intro)                                           DOC-11
The first line after the front matter must be the H1 (DOC-23).

Prints `path:line: DOC-n message — how to fix` for each problem. Standard library only
(Python 3.11).
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(
    subprocess.run(
        ["git", "-C", str(Path(__file__).resolve().parent), "rev-parse", "--show-toplevel"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
)
INDEX = ROOT / "docs/design/README.md"
INDEX_START = "<!-- index:start: generated by scripts/check.d/doc_meta.py --write; do not edit -->"
INDEX_END = "<!-- index:end -->"

STATUSES = ("draft", "accepted", "implemented", "superseded")
# Owner roles, in index order, with the index heading for each. A role, not a person: the people
# and agents behind a role change; the role does not (docs.md DOC-8).
OWNERS = {
    "architecture": "System",
    "protocol": "Protocol",
    "firmware": "Firmware",
    "daemon": "Daemon and host",
    "ui": "Watch UI",
    "tools": "Tools",
    "conventions": "Conventions",
}
REQUIRED = ("status", "owner", "last_reviewed")
KNOWN = (*REQUIRED, "issue", "superseded_by", "summary")
ISSUE_RE = re.compile(r"^\d{8}-[0-9a-f]{4}$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
KEY_RE = re.compile(r"^([a-z_]+):(?:\s+(.*?))?\s*$")


@dataclass
class Doc:
    """One checked Markdown file and what its front matter and opening say."""

    path: Path
    meta: dict[str, str | list[str]] = field(default_factory=dict)
    lines: dict[str, int] = field(default_factory=dict)  # key -> line number
    title: str = ""
    first_sentence: str = ""

    @property
    def rel(self) -> str:
        """The path from the repository root, with forward slashes."""
        return self.path.relative_to(ROOT).as_posix()

    def issues(self) -> list[str]:
        """The issue IDs the doc names, as a list."""
        v = self.meta.get("issue", [])
        return [v] if isinstance(v, str) else list(v)


def doc_paths() -> list[Path]:
    """The files DOC-8 covers: design docs (not the index) and convention pages (not templates)."""
    design = [p for p in (ROOT / "docs/design").rglob("*.md") if p != INDEX]
    conventions = list((ROOT / "docs/conventions").glob("*.md"))
    return sorted(design + conventions)


def scalar(raw: str) -> str:
    """A YAML scalar as this repo writes it: plain, 'single' or "double" quoted; # comments."""
    raw = raw.strip()
    if raw.startswith("'"):
        end = re.match(r"'((?:[^']|'')*)'", raw)
        return end.group(1).replace("''", "'") if end else raw
    if raw.startswith('"'):
        end = re.match(r'"((?:[^"\\]|\\.)*)"', raw)
        return re.sub(r"\\(.)", r"\1", end.group(1)) if end else raw
    return re.sub(r"\s+#.*$", "", raw).strip()


def parse(path: Path, errors: list[str]) -> Doc:
    """Read a doc's front matter (a small YAML subset), its H1 and its first sentence."""
    doc = Doc(path)
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    if not lines or lines[0] != "---":
        errors.append(
            f"{doc.rel}:1: DOC-8 no front matter — start the file with a '---' block "
            "(docs/conventions/docs.md §2, templates/design-doc.md)"
        )
        return doc
    try:
        end = lines.index("---", 1)
    except ValueError:
        errors.append(f"{doc.rel}:1: DOC-8 front matter is not closed — add a '---' line after it")
        return doc
    for n, line in enumerate(lines[1:end], start=2):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = KEY_RE.match(line)
        if not m:
            errors.append(f"{doc.rel}:{n}: DOC-8 cannot read '{line}' — write 'key: value'")
            continue
        key, raw = m.group(1), m.group(2) or ""
        if key in doc.meta:
            errors.append(f"{doc.rel}:{n}: DOC-8 '{key}' given twice — keep one")
        if raw.startswith("["):
            inner = re.sub(r"\s+#.*$", "", raw).strip()
            if not inner.endswith("]"):
                errors.append(f"{doc.rel}:{n}: DOC-8 list not closed — write [a, b] on one line")
                continue
            doc.meta[key] = [scalar(v) for v in inner[1:-1].split(",") if v.strip()]
        else:
            doc.meta[key] = scalar(raw)
        doc.lines[key] = n
    body = lines[end + 1 :]
    first = next((i for i, line in enumerate(body) if line.strip()), None)
    if first is None or not body[first].startswith("# "):
        errors.append(
            f"{doc.rel}:{end + 2}: DOC-23 the H1 must follow the front matter — add '# Title'"
        )
    else:
        doc.title = body[first][2:].strip()
        doc.first_sentence = intro_sentence(body[first + 1 :])
    return doc


def intro_sentence(body: list[str]) -> str:
    """The first sentence of the first plain paragraph before the first section heading."""
    para: list[str] = []
    for line in [*body, ""]:
        if line.startswith("#"):
            break
        if line.strip():
            para.append(line.strip())
            continue
        text = " ".join(para)
        para = []
        if not text or text.startswith((">", "<!--", "Status:", "**", "- ", "|")):
            continue
        m = re.match(r"(.+?[.!?])(?:\s|$)", text)
        return m.group(1) if m else text
    return ""


def validate(docs: list[Doc], errors: list[str]) -> None:
    """DOC-8, DOC-9, DOC-10: required fields, allowed values, real dates, targets that exist."""
    issue_ids = {p.name[:13] for p in (ROOT / "issues").glob("2*.md")}
    checked = {d.path.resolve() for d in docs}
    today = dt.date.today()
    for d in docs:
        if not d.lines:
            continue  # no front matter: already reported
        first = min(d.lines.values())

        def err(key: str, rule: str, msg: str, d: Doc = d, first: int = first) -> None:
            errors.append(f"{d.rel}:{d.lines.get(key, first)}: {rule} {msg}")

        for key in d.meta:
            if key not in KNOWN:
                err(key, "DOC-8", f"unknown field '{key}' — use only {', '.join(KNOWN)}")
        for key in REQUIRED:
            if key not in d.meta:
                err(key, "DOC-8", f"missing '{key}' — add it (docs/conventions/docs.md §2)")
        status = d.meta.get("status")
        if status is not None and status not in STATUSES:
            err("status", "DOC-9", f"status '{status}' — use one of {' | '.join(STATUSES)}")
        owner = d.meta.get("owner")
        if owner is not None and owner not in OWNERS:
            err("owner", "DOC-8", f"owner '{owner}' — use a role: {', '.join(OWNERS)}")
        date = d.meta.get("last_reviewed")
        if isinstance(date, str):
            try:
                if not DATE_RE.match(date):
                    raise ValueError
                when = dt.date.fromisoformat(date)
            except ValueError:
                err("last_reviewed", "DOC-10", f"'{date}' is not a date — write YYYY-MM-DD")
            else:
                if when > today + dt.timedelta(days=1):
                    err("last_reviewed", "DOC-10", f"{date} is in the future — use today's date")
        for issue in d.issues():
            if not ISSUE_RE.match(issue):
                err("issue", "DOC-8", f"'{issue}' is not an issue ID — write YYYYMMDD-xxxx")
            elif issue not in issue_ids:
                err("issue", "DOC-8", f"no issues/{issue}-*.md — check the ID (scripts/issue list)")
        sup = d.meta.get("superseded_by")
        if status == "superseded" and not sup:
            err("status", "DOC-9", "superseded needs superseded_by — name the replacement doc")
        if sup and status != "superseded":
            err("superseded_by", "DOC-9", "superseded_by without status superseded — drop one")
        if isinstance(sup, str) and sup:
            target = (d.path.parent / sup).resolve()
            if target not in checked:
                err("superseded_by", "DOC-9", f"'{sup}' is not a doc here — give a relative path")
            elif target == d.path.resolve():
                err("superseded_by", "DOC-9", "a doc cannot supersede itself")
        for key, value in d.meta.items():
            if key != "issue" and isinstance(value, list):
                err(key, "DOC-8", f"'{key}' must be a single value, not a list")


def cell(text: str) -> str:
    """Escape a table cell's pipes so GitHub does not split it (DOC-29)."""
    return text.replace("|", "\\|")


def render_index(docs: list[Doc]) -> str:
    """The generated part of docs/design/README.md: one table per owner role."""
    issue_files = {p.name[:13]: p.name for p in (ROOT / "issues").glob("2*.md")}
    design = [d for d in docs if d.rel.startswith("docs/design/")]
    out = [INDEX_START, ""]
    for owner, heading in OWNERS.items():
        group = [d for d in design if d.meta.get("owner") == owner]
        if not group:
            continue
        out += [f"### {heading}", "", "| Doc | What it covers | Status | Issue | Reviewed |"]
        out.append("|---|---|---|---|---|")
        for d in group:
            rel = d.path.relative_to(INDEX.parent).as_posix()
            summary = d.meta.get("summary") or d.first_sentence or d.title
            status = str(d.meta.get("status", ""))
            sup = d.meta.get("superseded_by")
            if isinstance(sup, str) and sup:
                target = (d.path.parent / sup).resolve().relative_to(INDEX.parent).as_posix()
                status = f"superseded by [{Path(target).name}]({target})"
            issues = ", ".join(
                f"[{i[-4:]}](../../issues/{issue_files[i]})" if i in issue_files else i
                for i in d.issues()
            )
            row = [f"[{rel}]({rel})", cell(str(summary)), status, issues or "\u2013"]
            out.append("| " + " | ".join(row) + f" | {d.meta.get('last_reviewed', '')} |")
        out.append("")
    out.append(INDEX_END)
    return "\n".join(out)


def check_index(docs: list[Doc], write: bool, errors: list[str]) -> None:
    """DOC-11: the index between the markers is exactly what the front matter makes."""
    rel = INDEX.relative_to(ROOT).as_posix()
    text = INDEX.read_text(encoding="utf-8")
    start, end = text.find(INDEX_START), text.find(INDEX_END)
    if start < 0 or end < start:
        errors.append(
            f"{rel}:1: DOC-11 index markers missing — keep '{INDEX_START}' and '{INDEX_END}'"
        )
        return
    new = text[:start] + render_index(docs) + text[end + len(INDEX_END) :]
    if new == text:
        return
    if write:
        INDEX.write_text(new, encoding="utf-8")
        print(f"doc_meta: rewrote the index in {rel}")
    else:
        line = text[:start].count("\n") + 1
        errors.append(
            f"{rel}:{line}: DOC-11 the index is out of date — "
            "run python3 scripts/check.d/doc_meta.py --write"
        )


def stale(docs: list[Doc], days: int, status: str | None) -> None:
    """DOC-10 freshness report: info only."""
    cutoff = dt.date.today() - dt.timedelta(days=days)
    rows = []
    for d in docs:
        date = d.meta.get("last_reviewed")
        if status and d.meta.get("status") != status:
            continue
        try:
            when = dt.date.fromisoformat(str(date))
        except ValueError:
            continue
        if when < cutoff:
            rows.append((when, d))
    print(f"doc_meta: {len(rows)} doc(s) not reviewed since {cutoff} ({days} days)")
    for when, d in sorted(rows, key=lambda r: (r[0], r[1].rel)):
        age = (dt.date.today() - when).days
        print(f"{d.rel}: last_reviewed {when} ({age} days), status {d.meta.get('status')}")


def main() -> int:
    """Run the check, the --write regeneration or the --stale report."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true", help="rewrite the design-doc index")
    ap.add_argument("--stale", type=int, metavar="DAYS", help="list docs older than DAYS; exit 0")
    ap.add_argument("--status", choices=STATUSES, help="with --stale: only this status")
    args = ap.parse_args()
    if args.status and args.stale is None:
        ap.error("--status needs --stale")

    errors: list[str] = []
    docs = [parse(p, errors) for p in doc_paths()]
    if args.stale is not None:
        stale(docs, args.stale, args.status)
        return 0
    validate(docs, errors)
    if not any(e.split(":", 1)[0].startswith("docs/design/") for e in errors):
        check_index(docs, args.write, errors)
    elif args.write:
        errors.append("doc_meta: index not rewritten — fix the design docs' front matter first")
    for e in errors:
        print(e)
    if errors:
        print(f"doc_meta: {len(errors)} problem(s); docs/conventions/docs.md §2 says how to fix")
        return 1
    print(f"doc_meta: ok ({len(docs)} docs, index up to date)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
